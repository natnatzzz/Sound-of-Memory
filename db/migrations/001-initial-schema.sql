-- PostgreSQL equivalent of lib/db.js. Keep ISO date strings and JSON strings
-- as text so existing SQLite records can be imported without changing format.
CREATE TABLE IF NOT EXISTS public.sessions (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  age INTEGER NOT NULL,
  gender TEXT NOT NULL,
  location TEXT,
  user_agent TEXT,
  started_at TEXT NOT NULL,
  completed_at TEXT,
  status TEXT NOT NULL DEFAULT 'active',
  successful_rounds INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.rounds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id TEXT NOT NULL REFERENCES public.sessions(id),
  round_number INTEGER NOT NULL,
  sequence TEXT NOT NULL,
  digit_ms INTEGER NOT NULL DEFAULT 500,
  started_at BIGINT NOT NULL,
  answer TEXT,
  response_ms DOUBLE PRECISION,
  outcome TEXT,
  events TEXT,
  submitted_at TEXT,
  UNIQUE (session_id, round_number)
);

CREATE TABLE IF NOT EXISTS public.trials (
  id TEXT PRIMARY KEY,
  session_id TEXT NOT NULL REFERENCES public.sessions(id),
  scenario TEXT NOT NULL,
  position INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  successful_rounds INTEGER NOT NULL DEFAULT 0,
  started_at TEXT,
  completed_at TEXT,
  UNIQUE (session_id, scenario)
);

CREATE TABLE IF NOT EXISTS public.trial_rounds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trial_id TEXT NOT NULL REFERENCES public.trials(id),
  round_number INTEGER NOT NULL,
  sequence TEXT NOT NULL,
  digit_ms INTEGER NOT NULL,
  started_at BIGINT NOT NULL,
  volume DOUBLE PRECISION NOT NULL,
  answer TEXT,
  response_ms DOUBLE PRECISION,
  outcome TEXT,
  events TEXT,
  submitted_at TEXT,
  UNIQUE (trial_id, round_number)
);
